package app.readly.input.sites

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test

/**
 * Real-archive import report and bundled-catalog generator. Both tests run
 * only when `-Dreadly.sitesZip=/path/to/upstream.zip` points at a local
 * copy of the official archive (no network); otherwise they skip. The
 * writer additionally requires `-Dreadly.writeBundle=true`, so ordinary
 * suites never touch the bundled asset.
 *
 * This is the production-importer driver the shared-engine plan calls
 * for: the bundled catalog is generated by [SitesImporter] itself, never
 * by a separate reimplementation.
 */
class SiteBundleReportTest {
    private fun sitesZip(): File? {
        val path = System.getProperty("readly.sitesZip")
            ?: System.getenv("READLY_SITES_ZIP")
            ?: return null
        val file = File(path)
        return file.takeIf { it.isFile }
    }

    private fun importReal(): SiteCatalog {
        val zip = sitesZip()
        assumeTrue("set READLY_SITES_ZIP=/path/to/upstream.zip to run the real-archive report", zip != null)
        val bytes = zip?.readBytes() ?: throw AssertionError("unreachable")
        val sha = sha256Hex(bytes)
        return SitesImporter.importZip(bytes, sha, SiteCatalog.OFFICIAL_UPDATE_URL)
    }

    @Test
    fun realArchiveImportReport() {
        val catalog = importReal()
        val rules = catalog.rules
        val domains = rules.sumOf { it.matchDomains.size }
        val withRequest = rules.count { it.request.hasEffect() }
        val withCleanup = rules.count { it.html.cleanup.isNotEmpty() }
        val full = rules.count { it.status == RuleStatus.FULL }
        val partial = rules.count { it.status == RuleStatus.PARTIAL }
        val withheld = rules.count { rule -> rule.notes.any { it.contains("withheld") } }

        println("READLY-REPORT rules=${rules.size} domains=$domains withRequest=$withRequest " +
            "withCleanup=$withCleanup full=$full partial=$partial skipped=${catalog.skipped.size} " +
            "withheldNotes=$withheld version=${catalog.meta.version}")
        val skippedKinds = catalog.skipped.groupingBy { reasonKind(it.reason) }.eachCount()
        println("READLY-REPORT skippedKinds=$skippedKinds")
        println("READLY-REPORT licenseChars=${catalog.meta.license.length}")
        for (rule in rules.filter { r -> r.notes.any { it.contains("withheld") } }) {
            println("READLY-REPORT withheld ${rule.siteKey} :: " +
                rule.notes.first { it.contains("withheld") }.take(160))
        }

        // Representative imported publishers (import checks, not live-read PASS).
        val nyt = catalog.findRule("nytimes.com")
        assertNotNull("NYT rule missing", nyt)
        assertEquals(SiteTestFixtures.NYT_UA, nyt!!.request.userAgent)
        assertEquals("custom", nyt.request.userAgentSource)
        assertEquals(HostScope.APEX_AND_WWW, nyt.scope)
        assertNull("NYT must not broaden to cooking", catalog.findRule("cooking.nytimes.com"))

        val berliner = catalog.findRule("berliner-zeitung.de")
        assertNotNull("Berliner Zeitung rule missing", berliner)
        assertEquals(SiteTestFixtures.GOOGLEBOT_UA, berliner!!.request.userAgent)
        assertEquals("googlebot", berliner.request.userAgentSource)

        val bt = catalog.findRule("bt.no")
        assertNotNull("Bergens Tidende rule missing", bt)
        assertEquals(
            "facebookexternalhit/1.1 (+http://www.facebook.com/externalhit_uatext.php)",
            bt!!.request.userAgent,
        )

        val ft = catalog.findRule("ft.com")
        assertNotNull("FT rule missing", ft)
        assertEquals("https://www.google.com/", ft!!.request.referer)
        assertEquals("google", ft.request.refererSource)

        // Group/exception replacement: dn.se drops the parent googlebot UA.
        val dn = catalog.findRule("dn.se")
        assertNotNull("dn.se exception rule missing", dn)
        assertNull("dn.se exception must not inherit parent UA", dn!!.request.userAgent)
        val hd = catalog.findRule("hd.se")
        assertNotNull("hd.se group rule missing", hd)
        assertEquals(SiteTestFixtures.GOOGLEBOT_UA, hd!!.request.userAgent)

        assertTrue("expected hundreds of rules, got ${rules.size}", rules.size > 200)
        assertTrue("expected skipped settings/infra records", catalog.skipped.isNotEmpty())
        assertTrue("expected a MIT license from the archive", catalog.meta.license.startsWith("MIT License"))
    }

    @Test
    fun writeBundledCatalog() {
        assumeTrue(
            "set READLY_WRITE_BUNDLE=true to regenerate the bundled catalog",
            System.getProperty("readly.writeBundle") == "true" || System.getenv("READLY_WRITE_BUNDLE") == "true",
        )
        val catalog = importReal()
        assertTrue("bundled catalog needs the upstream MIT license", catalog.meta.license.startsWith("MIT License"))
        // Round-trip through the strict cache codec so only codec-valid data ships.
        val decoded = SiteCatalogJson.decode(SiteCatalogJson.encode(catalog), "Bundled catalog")
        assertEquals(catalog.rules.size, decoded.rules.size)
        assertEquals(catalog.skipped.size, decoded.skipped.size)
        val out = File("src/main/assets/sites/site_catalog.json").absoluteFile
        out.parentFile.mkdirs()
        out.writeText(SiteCatalogJson.encode(decoded) + "\n", Charsets.UTF_8)
        println("READLY-REPORT wrote ${out.path} bytes=${out.length()} " +
            "rules=${decoded.rules.size} skipped=${decoded.skipped.size}")
    }

    private fun reasonKind(reason: String): String = when {
        "infrastructure rule" in reason -> "infra"
        "settings marker" in reason -> "settings"
        "empty opt-in group" in reason -> "empty-group"
        "duplicate" in reason -> "duplicate"
        "withheld" in reason || "conflicting" in reason -> "conflict"
        "catalog is full" in reason || "catalog bound" in reason -> "bound"
        "unterminated" in reason || "not a static object" in reason || "unsupported suffix" in reason -> "shape"
        else -> "other"
    }

    private fun sha256Hex(bytes: ByteArray): String {
        val digest = java.security.MessageDigest.getInstance("SHA-256").digest(bytes)
        return digest.joinToString("") { "%02x".format(it) }
    }
}
